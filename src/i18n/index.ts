export const DICTS = { zh, en }

export function useT() {
  const locale = useGame((s) => s.settings.uiLocale)
  const dict = DICTS[locale] ?? zh
  return (key: string): string => dict[key] ?? zh[key] ?? key
}

export function useLocale() {
  return useGame((s) => s.settings.uiLocale)
}

export function pick<T>(v: { zh: T; en: T }, locale: 'zh' | 'en'): T {
  return v[locale] ?? v.zh
}
